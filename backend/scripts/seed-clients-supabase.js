// Generate unique 10-digit Indian mobile numbers
function generateMobileNumbers(count) {
  const mobileNumbers = new Set();
  while (mobileNumbers.size < count) {
    // Generate 10-digit number starting with 7, 8, or 9 (valid Indian mobile numbers)
    const firstDigit = Math.floor(Math.random() * 3) + 7; // 7, 8, or 9
    const restDigits = Math.floor(Math.random() * 1000000000).toString().padStart(9, '0');
    const mobileNumber = firstDigit + restDigits;
    mobileNumbers.add(mobileNumber);
  }
  return Array.from(mobileNumbers);
}

async function seedClients() {
  try {
    console.log('🚀 Starting client seeding to Supabase...');
    
    const mobileNumbers = generateMobileNumbers(clientNames.length);
    
    let successCount = 0;
    let skipCount = 0;
    
    for (let i = 0; i < clientNames.length; i++) {
      const name = clientNames[i];
      const phone = mobileNumbers[i];
      
      try {
        // Check if client already exists
        const existing = await prisma.party.findFirst({
          where: {
            name: name,
            city: 'JND'
          }
        });
        
        if (existing) {
          console.log(`⏭️  Skipping: ${name} (already exists)`);
          skipCount++;
          continue;
        }
        
        // Create new client
        await prisma.party.create({
          data: {
            name: name,
            phone: phone,
            city: 'JND',
            isActive: true,
            isDeleted: false
          }
        });
        
        console.log(`✅ Created: ${name} - Phone: ${phone}`);
        successCount++;
        
      } catch (error) {
        console.error(`❌ Error creating ${name}:`, error.message);
      }
    }
    
    console.log('\n📊 Seeding Summary:');
    console.log(`✅ Successfully created: ${successCount} clients`);
    console.log(`⏭️  Skipped (already exists): ${skipCount} clients`);
    console.log(`📝 Total processed: ${clientNames.length} clients`);
    
  } catch (error) {
    console.error('❌ Error seeding clients:', error);
  } finally {
    await prisma.$disconnect();
  }
}

seedClients();
